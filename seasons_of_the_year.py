s = input("Введите время года (лето, осень, зима, весна): ")

if s == "лето":
    print("Отличное время для отдыха на пляже!")
elif s == "осень":
    print("Прекрасное время для прогулок.")
elif s == "зима":
    print("Замечательное время для катания на лыжах.")
elif s == "весна":
    print("Время пробуждения природы.")
else:
    print("Вы ввели не время года.")
